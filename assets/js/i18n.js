(function () {
  var T = { zh: 'zh', en: 'en' };

  window.I18N = {
    lang: 'zh',
    dict: window.XX_I18N,
    /** 取字串，支援 {{param}} 插值 */
    t: function (key, params) {
      var pack = this.dict[this.lang] || this.dict.zh;
      var s = pack[key];
      if (s == null) s = this.dict.zh[key];
      if (s == null) s = key;
      if (params) {
        s = s.replace(/\{\{\s*(\w+)\s*\}\}/g, function (_, k) {
          return params[k] != null ? String(params[k]) : '';
        });
      }
      return s;
    },
    /** 依 config 的 brand / 角色名稱取当前語言值 */
    brand: function () {
      var b = (window.XX_CONFIG.site && XX_CONFIG.site.brand) || {};
      return b[this.lang] || b.zh || '修仙也要拍';
    },
    charName: function (c) { if (!c) return ''; return c[this.lang] || c.zh || c.id; },
    isZh: function () { return this.lang === 'zh'; },
    set: function (lang) { this.lang = T[lang] ? lang : 'zh'; }
  };
}());
